export function lookupShippingJpy(method: ShippingMethod, grams: number): number | null {
  if (grams > method.maxG) return null;
  if (grams < method.minG) return null;
  for (const [maxG, jpy] of method.bands) {
    if (grams <= maxG) return jpy;
  }
  return null;
}
